/**
 * getChatScenario(scenarioKey, targetLang, preferredLang)
 * Helper to retrieve localized scenario data with fallback protection.
 */
function getChatScenario(scenarioKey, targetLang, preferredLang) {
  const data = CHAT_SCENARIOS_DATA[scenarioKey];
  if (!data) return null;

  const tLang = targetLang || "en";
  const pLang = preferredLang || "en";

  const title = (data.titles && data.titles[pLang]) || data.titles?.en || "Conversation Practice";
  const desc = (data.descriptions && data.descriptions[pLang]) || data.descriptions?.en || "";
  const contact = (data.contacts && data.contacts[pLang]) || data.contacts?.en || { name: "Assistant", role: "Support" };
  const task = (data.tasks && data.tasks[pLang]) || data.tasks?.en || "Complete the scenario.";
  const successMsg = (data.successMessages && data.successMessages[pLang]) || data.successMessages?.en || "Great job!";

  const turns = (data.turns || []).map((t, idx) => {
    const incomingText = (t.incoming && t.incoming[tLang]) || t.incoming?.en || "";
    const incomingTranslation = (t.incoming && t.incoming[pLang]) || t.incoming?.en || "";

    const rawOptions = (t.options && t.options[tLang]) || t.options?.en || [];
    const rawOptionsTranslations = (t.options && t.options[pLang]) || t.options?.en || [];

    const coachTip = (t.coachTips && t.coachTips[pLang]) || t.coachTips?.en || "Please select the most safe and polite response.";

    return {
      turnIndex: idx,
      incoming: incomingText,
      incomingTranslation: (pLang !== tLang) ? incomingTranslation : "",
      options: rawOptions,
      optionsTranslations: (pLang !== tLang) ? rawOptionsTranslations : [],
      correctIndex: typeof t.correctIndex === "number" ? t.correctIndex : 0,
      coachTip: coachTip
    };
  });

  return {
    id: data.id,
    icon: data.icon,
    category: data.category,
    turnsCount: data.turnsCount || turns.length,
    title: title,
    desc: desc,
    contactName: contact.name,
    contactRole: contact.role,
    task: task,
    successMessage: successMsg,
    turns: turns
  };
}

function applyTranslations(langCode) {
  const lang = translations[langCode] || translations["en"];

  document.querySelectorAll("[data-i18n]").forEach(function (element) {
    const key = element.getAttribute("data-i18n");
    if (lang[key]) {
      element.textContent = lang[key];
    }
  });

  document
    .querySelectorAll("[data-i18n-placeholder]")
    .forEach(function (element) {
      const key = element.getAttribute("data-i18n-placeholder");
      if (lang[key]) {
        element.placeholder = lang[key];
      }
    });

  document.querySelectorAll("[data-i18n-option]").forEach(function (element) {
    const key = element.getAttribute("data-i18n-option");
    if (lang[key]) {
      element.textContent = lang[key];
    }
  });
}

/**
 * getTranslation(langCode, key)
 * Helper to grab a single translated string by key.
 */
function getTranslation(langCode, key) {
  const lang = translations[langCode] || translations["en"];
  return lang[key] || translations["en"][key] || key;
}
